"""Split a video into short time windows for the ML team to score."""
import json
import subprocess


def get_duration(video_path):
    """Return the video's length in seconds, using ffprobe."""
    result = subprocess.run(
        [
            "ffprobe",
            "-v", "error",                       # only print real errors
            "-show_entries", "format=duration",  # we only want the duration
            "-of", "json",                       # machine-readable output
            str(video_path),
        ],
        capture_output=True,
        text=True,
        check=True,  # raises CalledProcessError if ffprobe fails (bad path, not a video)
    )
    data = json.loads(result.stdout)
    return float(data["format"]["duration"])


def make_windows(duration, window_size=2.5):
    """Return a list of (start, end) pairs covering the whole video.

    The last window is clipped so it never goes past the end of the video.
    """
    if window_size <= 0:
        raise ValueError("window_size must be positive")
    if duration <= 0:
        return []

    windows = []
    i = 0
    while True:
        # i * window_size (instead of adding 2.5 over and over) avoids float drift
        start = round(i * window_size, 3)
        if start >= duration:
            break
        end = round(min(start + window_size, duration), 3)
        windows.append((start, end))
        i += 1
    return windows


def save_windows(chunk_id, windows, client):
    """Insert each window as a row in the Supabase `windows` table.

    `client` is a Supabase client (from supabase import create_client).
    Passing it in, instead of creating it here, lets the tests use a fake one.
    """
    if not windows:
        return []

    # Columns from SIG-34. `id` is generated by Supabase; `score` stays null
    # until the ML team fills it in.
    rows = [
        {
            "chunk_id": chunk_id,
            "start_seconds": start,
            "end_seconds": end,
        }
        for start, end in windows
    ]
    # one bulk insert instead of ~120 separate requests
    response = client.table("windows").insert(rows).execute()
    return response.data
